const dictionaries: Record<Locale, Record<Key, string>> = { "zh-Hant": zhHant, "zh-Hans": zhHans, en };

const LOCALE_STORAGE_KEY = "speakmate.locale";

function isLocale(value: string | null): value is Locale {
  return value === "zh-Hant" || value === "zh-Hans" || value === "en";
}

function detectDefaultLocale(): Locale {
  const stored = typeof window !== "undefined" ? localStorage.getItem(LOCALE_STORAGE_KEY) : null;
  if (isLocale(stored)) return stored;

  const nav = typeof navigator !== "undefined" ? navigator.language.toLowerCase() : "";
  if (nav.startsWith("zh-cn") || nav.startsWith("zh-sg") || nav.includes("hans")) return "zh-Hans";
  if (nav.startsWith("zh")) return "zh-Hant";
  if (nav.startsWith("en")) return "en";
  return "zh-Hant";
}

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, k: string) => String(vars[k] ?? ""));
}

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  // Looks up "error.<code>" with a fallback to error.generic — for server
  // error codes, which aren't known at compile time.
  terr: (code?: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => detectDefaultLocale());

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    localStorage.setItem(LOCALE_STORAGE_KEY, next);
  }, []);

  const t = useCallback(
    (key: Key, vars?: Record<string, string | number>) => interpolate(dictionaries[locale][key], vars),
    [locale]
  );

  const terr = useCallback(
    (code?: string) => {
      const dict = dictionaries[locale];
      const key = `error.${code}` as Key;
      return code && key in dict ? dict[key] : dict["error.generic"];
    },
    [locale]
  );

  return <I18nContext.Provider value={{ locale, setLocale, t, terr }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
